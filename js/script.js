let nameAnimTimeout = null;

function initTypingAnimation() {
  const holder = document.querySelector('.letter-holder');
  if (!holder) return;

  if (nameAnimTimeout) {
    clearTimeout(nameAnimTimeout);
  }

  const textToAnimate = 'SATRIYA BAYUAJI RAHMATULLAH';
  holder.innerHTML = '';

  textToAnimate.split('').forEach((char) => {
    const span = document.createElement('span');
    span.textContent = char === ' ' ? '\u00A0' : char;
    span.className = 'animated-letter';
    holder.appendChild(span);
  });

  const letters = holder.querySelectorAll('.animated-letter');
  let isForward = true;
  let currentIndex = 0;

  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
    letters.forEach((letter) => letter.classList.add('visible'));
    return;
  }

  function runLetterAnimation() {
    const activeHolder = document.querySelector('.letter-holder');
    if (!activeHolder) return;

    if (isForward) {
      if (currentIndex <= letters.length) {
        if (currentIndex > 0) {
          letters[currentIndex - 1].classList.add('visible');
        }
        currentIndex += 1;
        nameAnimTimeout = setTimeout(runLetterAnimation, 70);
      } else {
        isForward = false;
        nameAnimTimeout = setTimeout(runLetterAnimation, 1500);
      }
    } else {
      if (currentIndex >= 0) {
        if (currentIndex < letters.length) {
          letters[currentIndex].classList.remove('visible');
        }
        currentIndex -= 1;
        nameAnimTimeout = setTimeout(runLetterAnimation, 40);
      } else {
        isForward = true;
        currentIndex = 0;
        nameAnimTimeout = setTimeout(runLetterAnimation, 400);
      }
    }
  }

  runLetterAnimation();
}

document.addEventListener('DOMContentLoaded', () => {
  const savedTheme = localStorage.getItem('space_theme') || 'dark';
  document.documentElement.setAttribute('data-theme', savedTheme);
  updateThemeIcon(savedTheme);

  applyTranslations(getCurrentLang());

  const preloader = document.getElementById('preloader');
  if (preloader) {
    setTimeout(() => {
      preloader.style.opacity = '0';
      setTimeout(() => {
        preloader.style.display = 'none';
      }, 500);
    }, 800);
  }

  loadPage('home');

  document.addEventListener('click', (event) => {
    const toggler = event.target.closest('.navbar-toggler');
    if (toggler) {
      const targetSelector = toggler.getAttribute('data-bs-target') || toggler.getAttribute('data-target');
      if (targetSelector) {
        const targetEl = document.querySelector(targetSelector);
        if (targetEl && typeof bootstrap !== 'undefined') {
          let bsCollapse = bootstrap.Collapse.getInstance(targetEl);
          if (!bsCollapse) {
            bsCollapse = new bootstrap.Collapse(targetEl, { toggle: true });
          } else {
            bsCollapse.toggle();
          }
        }
      }
      return;
    }

    const targetLink = event.target.closest('[data-page]');
    if (targetLink) {
      event.preventDefault();
      const pageName = targetLink.getAttribute('data-page');
      loadPage(pageName);
      setActiveNav(targetLink);

      const navbarCollapse = document.getElementById('navbarNav');
      if (navbarCollapse && navbarCollapse.classList.contains('show') && typeof bootstrap !== 'undefined') {
        const bsCollapse = bootstrap.Collapse.getInstance(navbarCollapse);
        if (bsCollapse) {
          bsCollapse.hide();
        }
      }
    }
  });

  const themeToggleBtn = document.getElementById('theme-toggle');
  if (themeToggleBtn) {
    themeToggleBtn.addEventListener('click', () => {
      const currentTheme = document.documentElement.getAttribute('data-theme');
      const newTheme = currentTheme === 'dark' ? 'light' : 'dark';
      document.documentElement.setAttribute('data-theme', newTheme);
      localStorage.setItem('space_theme', newTheme);
      updateThemeIcon(newTheme);
      applyTranslations(getCurrentLang());
    });
  }

  const langToggleBtn = document.getElementById('lang-toggle');
  if (langToggleBtn) {
    langToggleBtn.addEventListener('click', () => {
      const newLang = getCurrentLang() === 'id' ? 'en' : 'id';
      applyTranslations(newLang);
    });
  }

  const backToTopBtn = document.getElementById('back-to-top');
  if (backToTopBtn) {
    backToTopBtn.addEventListener('click', () => {
      window.scrollTo({ top: 0, behavior: 'smooth' });
    });
  }
});
