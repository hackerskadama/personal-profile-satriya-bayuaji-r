class StarField {
  constructor() {
    this.canvas = document.getElementById('space-canvas');
    if (!this.canvas) return;
    this.ctx = this.canvas.getContext('2d');
    this.stars = [];
    this.shootingStars = [];
    this.numStars = window.innerWidth < 768 ? 60 : 150;
    this.init();
    this.animate();
    window.addEventListener('resize', () => this.resize());
  }

  init() {
    this.resize();
    for (let i = 0; i < this.numStars; i++) {
      this.stars.push({
        x: Math.random() * this.canvas.width,
        y: Math.random() * this.canvas.height,
        radius: Math.random() * 1.5 + 0.5,
        alpha: Math.random(),
        speed: Math.random() * 0.02 + 0.005
      });
    }
  }

  resize() {
    if (!this.canvas) return;
    this.canvas.width = window.innerWidth;
    this.canvas.height = window.innerHeight;
  }

  addShootingStar() {
    if (Math.random() < 0.03 && this.shootingStars.length < 2) {
      this.shootingStars.push({
        x: Math.random() * this.canvas.width,
        y: 0,
        length: Math.random() * 80 + 40,
        speed: Math.random() * 10 + 6,
        opacity: 1
      });
    }
  }

  animate() {
    if (!this.canvas) return;
    this.ctx.clearRect(0, 0, this.canvas.width, this.canvas.height);

    this.stars.forEach((star) => {
      star.alpha += star.speed;
      if (star.alpha > 1 || star.alpha < 0.2) {
        star.speed = -star.speed;
      }
      this.ctx.beginPath();
      this.ctx.arc(star.x, star.y, star.radius, 0, Math.PI * 2);
      this.ctx.fillStyle = 'rgba(255, 255, 255, ' + Math.abs(star.alpha) + ')';
      this.ctx.fill();
    });

    this.addShootingStar();

    this.shootingStars.forEach((ss, index) => {
      ss.x -= ss.speed;
      ss.y += ss.speed;
      ss.opacity -= 0.02;

      this.ctx.beginPath();
      this.ctx.moveTo(ss.x, ss.y);
      this.ctx.lineTo(ss.x + ss.length, ss.y - ss.length);
      this.ctx.strokeStyle = 'rgba(124, 140, 255, ' + ss.opacity + ')';
      this.ctx.lineWidth = 2;
      this.ctx.stroke();

      if (ss.opacity <= 0 || ss.y > this.canvas.height) {
        this.shootingStars.splice(index, 1);
      }
    });

    requestAnimationFrame(() => this.animate());
  }
}

function getCurrentLang() {
  const saved = localStorage.getItem('space_lang');
  return saved === 'en' ? 'en' : 'id';
}

function translateText(key, fallback = '') {
  const lang = getCurrentLang();
  const current = translations[lang] || translations.id;
  return current[key] || translations.id[key] || fallback;
}

function updateThemeIcon(theme) {
  const icon = document.getElementById('theme-icon');
  if (icon) {
    icon.className = theme === 'light' ? 'bi bi-sun-fill text-warning' : 'bi bi-moon-stars-fill text-info';
  }
}

function updateLanguageToggle() {
  const langToggle = document.getElementById('lang-toggle');
  if (!langToggle) return;

  const currentLang = getCurrentLang();
  langToggle.textContent = currentLang === 'en' ? 'EN | ID' : 'ID | EN';
  langToggle.setAttribute('aria-label', currentLang === 'en' ? 'Switch language to Indonesian' : 'Switch language to English');
}

function applyTranslations(lang) {
  const selectedLang = translations[lang] ? lang : 'id';
  localStorage.setItem('space_lang', selectedLang);
  document.documentElement.lang = selectedLang === 'en' ? 'en' : 'id';

  document.querySelectorAll('[data-translate]').forEach((el) => {
    const key = el.getAttribute('data-translate');
    const value = (translations[selectedLang] && translations[selectedLang][key]) || translations.id[key];
    if (value) {
      el.textContent = value;
    }
  });

  document.querySelectorAll('[data-translate-attr]').forEach((el) => {
    const definitions = el.getAttribute('data-translate-attr').split(';');
    definitions.forEach((definition) => {
      const [attribute, key] = definition.split(':');
      if (!attribute || !key) return;
      const value = (translations[selectedLang] && translations[selectedLang][key]) || translations.id[key];
      if (value) el.setAttribute(attribute.trim(), value);
    });
  });

  document.querySelectorAll('[data-translate-aria-label]').forEach((el) => {
    const key = el.getAttribute('data-translate-aria-label');
    const value = (translations[selectedLang] && translations[selectedLang][key]) || translations.id[key];
    if (value) el.setAttribute('aria-label', value);
  });

  const pageTitle = document.querySelector('[data-page-title]');
  if (pageTitle && translations[selectedLang].page_title) {
    pageTitle.textContent = translations[selectedLang].page_title;
    document.title = translations[selectedLang].page_title;
  }

  const journeyTimeline = document.querySelector('.journey-timeline[data-translate-aria-label]');
  if (journeyTimeline) {
    journeyTimeline.setAttribute('aria-label', translateText('journey_timeline_aria', 'Education journey timeline'));
  }

  const navToggler = document.querySelector('.navbar-toggler');
  if (navToggler) {
    navToggler.setAttribute('aria-label', selectedLang === 'en' ? 'Toggle navigation' : 'Alihkan navigasi');
  }

  const themeToggle = document.getElementById('theme-toggle');
  if (themeToggle) {
    const currentTheme = document.documentElement.getAttribute('data-theme') || 'dark';
    themeToggle.setAttribute('aria-label', currentTheme === 'dark' ? (selectedLang === 'en' ? 'Switch to light mode' : 'Alihkan ke mode terang') : (selectedLang === 'en' ? 'Switch to dark mode' : 'Alihkan ke mode gelap'));
  }

  const preloaderText = document.getElementById('preloader-text');
  if (preloaderText) {
    preloaderText.textContent = translations[selectedLang].preloader_text;
  }

  const lightbox = document.getElementById('hobi-lightbox');
  if (lightbox) {
    const dialog = lightbox.querySelector('.hobi-lightbox-dialog');
    const image = lightbox.querySelector('.hobi-lightbox-image');
    const closeButton = lightbox.querySelector('.hobi-lightbox-close');
    if (dialog) dialog.setAttribute('aria-label', translateText('hobi_lightbox_dialog_label', 'Hobby photo preview'));
    if (image) image.setAttribute('alt', translateText('hobi_lightbox_image_alt', 'Hobby photo preview'));
    if (closeButton) closeButton.setAttribute('aria-label', translateText('hobi_lightbox_close', 'Close photo preview'));
  }

  const backToTop = document.getElementById('back-to-top');
  if (backToTop) {
    backToTop.setAttribute('aria-label', translations[selectedLang].back_to_top || 'Back to Top');
  }

  const detailView = document.getElementById('hobi-detail-view');
  if (detailView && detailView.dataset.folderKey) {
    openHobiFolder(detailView.dataset.folderKey);
  }

  updateLanguageToggle();
}

function loadPage(pageName) {
  const mainContent = document.getElementById('main-content');
  if (!mainContent) return;

  mainContent.style.opacity = '0';
  mainContent.style.transform = 'translateY(15px)';

  fetch(`pages/${pageName}.html`)
    .then((response) => {
      if (!response.ok) throw new Error('Page not found');
      return response.text();
    })
    .then((html) => {
      mainContent.innerHTML = html;
      applyTranslations(getCurrentLang());

      if (pageName === 'home') {
        setTimeout(() => initTypingAnimation(), 80);
      }

      if (pageName === 'hobi') {
        initHobiAssetPaths();
      }

      if (typeof AOS !== 'undefined') {
        AOS.init({ duration: 800, once: true });
      }

      mainContent.style.opacity = '1';
      mainContent.style.transform = 'translateY(0)';
      window.scrollTo({ top: 0, behavior: 'smooth' });
    })
    .catch(() => {
      const currentLang = getCurrentLang();
      mainContent.innerHTML = '<div class="text-center py-5"><h3 class="text-danger">' + translations[currentLang].error_load_page + '</h3></div>';
      mainContent.style.opacity = '1';
      mainContent.style.transform = 'translateY(0)';
    });
}

function setActiveNav(activeElement) {
  document.querySelectorAll('.navbar-nav .nav-link').forEach((link) => {
    link.classList.remove('active');
  });
  if (activeElement) {
    activeElement.classList.add('active');
  }
}

function resolveHobiAssetPath(fileName) {
  if (!fileName) return '';
  if (/^https?:\/\//i.test(fileName)) return fileName;

  const normalizedPath = fileName.replace(/\\/g, '/').replace(/^\.\//, '');
  const insidePagesFolder = window.location.pathname.includes('/pages/');
  const basePath = insidePagesFolder ? '../' : '';
  return `${basePath}${encodeURI(normalizedPath)}`;
}

function initHobiAssetPaths() {
  document.querySelectorAll('[data-hobi-image]').forEach((element) => {
    const fileName = element.getAttribute('data-hobi-image');
    if (!fileName) return;
    element.src = resolveHobiAssetPath(fileName);
  });
}

