  const detailView = document.getElementById('hobi-detail-view');
  const titleEl = document.getElementById('detail-folder-title');
  const descEl = document.getElementById('detail-folder-desc');
  const photoContainer = document.getElementById('detail-photos-container');

  if (!mainView || !detailView || !titleEl || !descEl || !photoContainer) return;

  detailView.dataset.folderKey = folderKey;
  mainView.classList.add('d-none');
  detailView.classList.remove('d-none');

  titleEl.textContent = collection.title;
  descEl.textContent = collection.description;

